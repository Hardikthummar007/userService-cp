package com.example.userService.battle.service;

import com.example.userService.battle.dto.MatchFoundDto;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.messaging.simp.SimpMessagingTemplate;
import org.springframework.stereotype.Service;

import java.util.*;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicLong;
import java.util.concurrent.locks.ReentrantLock;

/**
 * Service managing matchmaking for 1v1 coding battles.
 * Matches waiting players in a race-safe, FIFO queue.
 */
@Service
public class MatchmakingService {

    private static final Logger logger = LoggerFactory.getLogger(MatchmakingService.class);

    @Autowired
    private SimpMessagingTemplate messagingTemplate;

    @Autowired
    private BattleService battleService;

    // CONCURRENCY DECISION:
    // A single ReentrantLock protects queue modifications and pairing logic on this single instance.
    // In a multi-instance production environment, Redis (e.g. Redis List with LPUSH/RPOP or a Redis Lua script)
    // and Redis distributed locks (Redisson) would replace this in-memory lock and queue.
    private final ReentrantLock lock = new ReentrantLock();

    // In-memory FIFO queue preserving insertion order and uniqueness
    private final LinkedHashSet<String> waitingQueue = new LinkedHashSet<>();

    // Tracks usernames currently in an ongoing/active battle to prevent double-joining
    private final Set<String> activeBattlePlayers = ConcurrentHashMap.newKeySet();

    // Sequence for generating temporary/mock battle IDs in Phase 2
    // (In Phase 3, this will be generated by the MySQL Battle table auto-increment ID)
    private final AtomicLong battleIdSequence = new AtomicLong(1000);

    /**
     * User requests to join the matchmaking queue.
     * Returns true if successfully added or paired; false if already queued or in battle.
     */
    public boolean joinQueue(String username) {
        if (username == null || username.isBlank()) {
            return false;
        }

        lock.lock();
        try {
            // Rule: Ignore join if user is already queued
            if (waitingQueue.contains(username)) {
                logger.info("Matchmaking: User '{}' is already in queue. Ignoring join request.", username);
                return false;
            }

            // Rule: Ignore join if user is already in an ACTIVE battle
            if (activeBattlePlayers.contains(username)) {
                logger.info("Matchmaking: User '{}' is already in an active battle. Ignoring join request.", username);
                return false;
            }

            waitingQueue.add(username);
            logger.info("Matchmaking: User '{}' joined queue. Current queue size: {}", username, waitingQueue.size());

            // Check if we can pair two players
            attemptPairing();
            return true;
        } finally {
            lock.unlock();
        }
    }

    /**
     * User requests to leave the matchmaking queue.
     */
    public boolean leaveQueue(String username) {
        if (username == null) {
            return false;
        }

        lock.lock();
        try {
            boolean removed = waitingQueue.remove(username);
            if (removed) {
                logger.info("Matchmaking: User '{}' left queue. Current queue size: {}", username, waitingQueue.size());
            }
            return removed;
        } finally {
            lock.unlock();
        }
    }

    /**
     * Handles WebSocket disconnect event.
     */
    public void onDisconnect(String username) {
        if (username == null) {
            return;
        }

        lock.lock();
        try {
            if (waitingQueue.remove(username)) {
                logger.info("Matchmaking: User '{}' disconnected. Removed from waiting queue.", username);
            }
        } finally {
            lock.unlock();
        }
    }

    /**
     * Attempts to pair the first two distinct players in the queue.
     * Must be called inside lock.
     */
    private void attemptPairing() {
        if (waitingQueue.size() < 2) {
            return;
        }

        Iterator<String> iterator = waitingQueue.iterator();
        String player1 = iterator.next();
        String player2 = iterator.next();

        // Safety check: players must differ
        if (player1.equals(player2)) {
            waitingQueue.remove(player2);
            return;
        }

        // Remove paired players from the waiting queue
        waitingQueue.remove(player1);
        waitingQueue.remove(player2);

        // Mark them as active in battle
        activeBattlePlayers.add(player1);
        activeBattlePlayers.add(player2);

        // Delegate battle creation, persistence, problem selection and start countdown to BattleService
        battleService.createBattle(player1, player2);
    }

    public boolean isUserInQueue(String username) {
        lock.lock();
        try {
            return waitingQueue.contains(username);
        } finally {
            lock.unlock();
        }
    }

    public boolean isUserInActiveBattle(String username) {
        return activeBattlePlayers.contains(username);
    }

    public void removeActiveBattlePlayer(String username) {
        activeBattlePlayers.remove(username);
    }

    public int getQueueSize() {
        lock.lock();
        try {
            return waitingQueue.size();
        } finally {
            lock.unlock();
        }
    }
}
